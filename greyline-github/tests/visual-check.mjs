import { chromium } from 'playwright';
import fs from 'node:fs';

fs.mkdirSync('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
page.on('pageerror', (error) => errors.push(error.message));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/redesign-01-title.png', fullPage: true });
await page.getByRole('button', { name: '顯示設定' }).click();
await page.getByLabel('文字大小').fill('115');
await page.getByLabel('工作台縮放').fill('110');
await page.screenshot({ path: 'artifacts/redesign-02-settings.png', fullPage: true });
await page.getByRole('button', { name: '完成設定' }).click();
await page.getByRole('button', { name: /開始新的戰役/ }).click();
await page.screenshot({ path: 'artifacts/redesign-03-briefing.png', fullPage: true });
await page.getByRole('button', { name: /拉開窗板/ }).click();
await page.waitForSelector('.document-passport');
await page.waitForTimeout(1800);
await page.screenshot({ path: 'artifacts/redesign-04-game.png', fullPage: true });
console.log('documents', await page.locator('.document').count());
console.log('transcript', await page.locator('.transcript-paper').count());
console.log('map', await page.locator('.topdown-checkpoint').count());
await page.getByRole('button', { name: '手冊', exact: true }).click();
await page.waitForSelector('.open-handbook');
await page.screenshot({ path: 'artifacts/redesign-05-book.png', fullPage: true });
await page.getByRole('button', { name: '關閉桌面手冊' }).click();
const doc = page.locator('.document-passport');
const before = await doc.boundingBox();
await page.mouse.move(before.x + 40, before.y + 18);
await page.mouse.down();
await page.mouse.move(before.x + 100, before.y + 260, { steps: 8 });
await page.mouse.up();
await page.getByRole('button', { name: '問目的' }).click();
console.log('dialogue lines', await page.locator('.transcript-line').count());
await page.screenshot({ path: 'artifacts/redesign-06-organized.png', fullPage: true });
console.log('errors', errors);
await browser.close();
